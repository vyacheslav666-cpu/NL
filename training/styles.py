def arc(cx, cy, rx, ry, a0, a1, n=56, rot=0.0):
    t = np.linspace(np.radians(a0), np.radians(a1), n)
    x, y = rx*np.cos(t), ry*np.sin(t)
    c, s = np.cos(rot), np.sin(rot)
    return list(zip(cx + x*c - y*s, cy + x*s + y*c))

