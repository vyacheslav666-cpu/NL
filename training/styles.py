LAB = '0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ'

def report(weights, title):
    ch = {}
    for k in weights.files if hasattr(weights, 'files') else weights:
        n, p = k.split('_'); ch.setdefault(int(n), {})[p] = weights[k]
    print(f'\n=== {title} ===')
    ok = 0
    for lab, name, st in CASES:
        row, votes = [], []
        px = [[(x*280, y*280) for x, y in s] for s in st]   # в пиксели холста: extract() ждёт их
        for n in (8, 10, 16):
            w = ch[n]
            x = extract(px, n).ravel()
            a1 = np.maximum(x @ w['W1'].T + w['b1'], 0)
            z = a1 @ w['W2'].T + w['b2']
            e = np.exp(z - z.max()); p = e/e.sum()
            votes.append(int(p.argmax()))
            row.append(f"{n}:{LAB[p.argmax()]}({p.max()*100:.0f}%)")
        li = LAB.index(str(lab))
        good = sum(v == li for v in votes)
        ok += good
        mark = '✓' if good == 3 else ('~' if good else '✗')
        print(f'  {mark} {lab}  {name:42s} ' + '  '.join(row))
    print(f'  итого верных голосов: {ok}/{len(CASES)*3}')
